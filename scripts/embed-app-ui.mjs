// Generates src/network/app-assets.generated.ts from app-ui/ so the customer app ships INSIDE the compiled server module.
// A serverless bundle cannot be trusted to contain loose files; a module import always is. `--check` fails when stale.
import { readFileSync, writeFileSync } from "node:fs";

const FILES = ["index.html", "app.js", "app.css"];
const out = new URL("../src/network/app-assets.generated.ts", import.meta.url);
const FONTS = [
  "bricolage-grotesque-latin-wght-normal.woff2",
  "instrument-sans-latin-wght-normal.woff2",
  "ibm-plex-mono-latin-400-normal.woff2",
];
const fonts =
  "export const APP_FONTS: Readonly<Record<string, string>> = Object.freeze({\n" +
  FONTS.map(
    (f) =>
      `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(new URL(`../app-ui/fonts/${f}`, import.meta.url)).toString("base64"))},`,
  ).join("\n") +
  "\n});\n";
const body =
  "// GENERATED by scripts/embed-app-ui.mjs from app-ui/. Do not edit; run `npm run embed:app`.\n" +
  "export const APP_ASSETS: Readonly<Record<string, string>> = Object.freeze({\n" +
  FILES.map(
    (f) =>
      `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(new URL(`../app-ui/${f}`, import.meta.url), "utf8"))},`,
  ).join("\n") +
  "\n});\n" +
  fonts;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    /* missing */
  }
  if (current !== body) {
    console.error("app-assets.generated.ts is stale: run `npm run embed:app`");
    process.exit(1);
  }
  console.log("app assets up to date");
} else {
  writeFileSync(out, body);
  console.log("wrote src/network/app-assets.generated.ts");
}
